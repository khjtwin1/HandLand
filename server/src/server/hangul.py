"""한글 이름을 지문자 자모 순서로 쪼개기 (이름 퀘스트용)"""

# 초성 / 중성 / 종성 표 (유니코드 한글 음절 계산용)
CHO = "ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ"
JUNG = "ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ"
JONG = ["", "ㄱ", "ㄲ", "ㄳ", "ㄴ", "ㄵ", "ㄶ", "ㄷ", "ㄹ", "ㄺ", "ㄻ", "ㄼ", "ㄽ",
        "ㄾ", "ㄿ", "ㅀ", "ㅁ", "ㅂ", "ㅄ", "ㅅ", "ㅆ", "ㅇ", "ㅈ", "ㅊ", "ㅋ", "ㅌ", "ㅍ", "ㅎ"]

# 카드가 없는 자모를 기본 자모로 바꾸는 표
BASIC = {
    "ㄲ": "ㄱ", "ㄸ": "ㄷ", "ㅃ": "ㅂ", "ㅆ": "ㅅ", "ㅉ": "ㅈ",
    "ㅒ": "ㅑㅣ", "ㅖ": "ㅕㅣ", "ㅘ": "ㅗㅏ", "ㅙ": "ㅗㅐ", "ㅚ": "ㅗㅣ",
    "ㅝ": "ㅜㅓ", "ㅞ": "ㅜㅔ", "ㅟ": "ㅜㅣ", "ㅢ": "ㅡㅣ",
    "ㄳ": "ㄱㅅ", "ㄵ": "ㄴㅈ", "ㄶ": "ㄴㅎ", "ㄺ": "ㄹㄱ", "ㄻ": "ㄹㅁ", "ㄼ": "ㄹㅂ",
    "ㄽ": "ㄹㅅ", "ㄾ": "ㄹㅌ", "ㄿ": "ㄹㅍ", "ㅀ": "ㄹㅎ", "ㅄ": "ㅂㅅ",
}


def name_to_jamo(name: str) -> list[str]:
    """'김하진' -> ['ㄱ','ㅣ','ㅁ','ㅎ','ㅏ','ㅈ','ㅣ','ㄴ'] (한글이 아닌 글자는 건너뜀)"""
    result: list[str] = []
    for ch in name:
        code = ord(ch) - 0xAC00
        if not 0 <= code <= 11171:
            continue
        parts = [CHO[code // 588], JUNG[code % 588 // 28], JONG[code % 28]]
        for p in parts:
            for jamo in BASIC.get(p, p):
                result.append(jamo)
    return result
